using System;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using DemonWeave.Unity;
using UnityEditor;
using UnityEditor.Build;
using UnityEditor.Build.Reporting;
using UnityEngine;

namespace DemonWeave.Editor
{
    [InitializeOnLoad]
    internal static class QuestFactCodeGenerator
    {
        static QuestFactCodeGenerator()
        {
            Undo.undoRedoPerformed += () => {
                foreach (var guid in AssetDatabase.FindAssets("t:QuestFactTable"))
                    Queue(AssetDatabase.LoadAssetAtPath<QuestFactTable>(AssetDatabase.GUIDToAssetPath(guid)));
            };
            EditorApplication.playModeStateChanged += state => {
                if (state != PlayModeStateChange.ExitingEditMode) return;
                foreach (var guid in AssetDatabase.FindAssets("t:QuestFactTable"))
                {
                    var table = AssetDatabase.LoadAssetAtPath<QuestFactTable>(AssetDatabase.GUIDToAssetPath(guid));
                    var error = Status(table);
                    if (string.IsNullOrEmpty(error)) continue;
                    Debug.LogError(table.name + ": " + error, table);
                    EditorApplication.isPlaying = false;
                    break;
                }
            };
        }
        private static string Symbol(string label)
        {
            var parts = Regex.Split(label ?? "", @"[\s_-]+").Where(p => p.Length > 0);
            var symbol = string.Concat(parts.Select(p => char.ToUpperInvariant(p[0]) + p.Substring(1)));
            if (!Regex.IsMatch(symbol, @"^[A-Za-z_][A-Za-z0-9_]*$"))
                throw new ArgumentException("Use an English name for C# generation: " + label);
            return symbol;
        }
        private static string Marker(QuestFactTable table) => "// DemonWeave fact table: " + AssetDatabase.AssetPathToGUID(AssetDatabase.GetAssetPath(table));
        internal static string Render(QuestFactTable table)
        {
            var error = table.CheckConfiguration();
            if (!string.IsNullOrEmpty(error)) throw new ArgumentException(error);
            var type = Symbol(table.name);
            var entries = table.Entries.Select(f => (name: Symbol(f.Label), id: f.Id)).OrderBy(f => f.name, StringComparer.Ordinal).ToArray();
            if (entries.Any(f => f.name == type) || entries.GroupBy(f => f.name).Any(g => g.Count() > 1))
                throw new ArgumentException("Fact names must generate distinct members and differ from the table class name.");
            if (entries.Any(f => !Regex.IsMatch(f.id, @"^[A-Za-z0-9_-]+$")))
                throw new ArgumentException("Fact ID contains unsupported characters.");
            var text = new StringBuilder("// <auto-generated />\n" + Marker(table) + "\nusing DemonWeave.Unity;\n\nnamespace DemonWeave.Generated\n{\n    public static class " + type + "\n    {\n");
            foreach (var entry in entries)
                text.Append("        public static QuestFactReference ").Append(entry.name).Append(" => new QuestFactReference { Id = \"").Append(entry.id).Append("\" };\n");
            return text.Append("    }\n}\n").ToString();
        }
        private static string OutputPath(QuestFactTable table)
        {
            var path = table.GeneratedCodePath?.Replace('\\', '/');
            var root = Path.GetFullPath(Application.dataPath) + Path.DirectorySeparatorChar;
            if (string.IsNullOrWhiteSpace(path) || !path.StartsWith("Assets/", StringComparison.Ordinal) ||
                !path.EndsWith(".cs", StringComparison.OrdinalIgnoreCase) || !Path.GetFullPath(path).StartsWith(root, StringComparison.OrdinalIgnoreCase))
                throw new ArgumentException("Generated code must be a .cs file under this project's Assets folder.");
            return path;
        }
        internal static void Generate(QuestFactTable table)
        {
            var content = Render(table); var path = OutputPath(table);
            if (File.Exists(path))
            {
                var old = File.ReadAllText(path).Replace("\r\n", "\n");
                if (!old.StartsWith("// <auto-generated />\n" + Marker(table) + "\n", StringComparison.Ordinal))
                    throw new InvalidOperationException("Refusing to overwrite a file not generated for this fact table: " + path);
                if (old == content) return;
            }
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllText(path, content, new UTF8Encoding(false));
            AssetDatabase.ImportAsset(path);
        }
        internal static void ChooseAndGenerate(QuestFactTable table)
        {
            Render(table);
            if (string.IsNullOrEmpty(table.GeneratedCodePath))
            {
                var path = EditorUtility.SaveFilePanelInProject("Generate fact accessors", table.name + ".g", "cs", "Place this file in the gameplay assembly that uses it.");
                if (string.IsNullOrEmpty(path)) return;
                Undo.RecordObject(table, "Set fact code destination");
                table.GeneratedCodePath = path; EditorUtility.SetDirty(table);
            }
            Generate(table); AssetDatabase.SaveAssetIfDirty(table);
        }
        internal static void Queue(QuestFactTable table)
        {
            if (!table || string.IsNullOrEmpty(table.GeneratedCodePath)) return;
            EditorApplication.delayCall += () => {
                if (!table || EditorApplication.isPlayingOrWillChangePlaymode) return;
                try { Generate(table); } catch (Exception e) { Debug.LogError(e.Message, table); }
            };
        }
        internal static string Status(QuestFactTable table)
        {
            if (string.IsNullOrEmpty(table.GeneratedCodePath)) return "";
            try {
                var text = Render(table); var path = OutputPath(table);
                return File.Exists(path) && File.ReadAllText(path).Replace("\r\n", "\n") == text ? ""
                    : "Generated C# is out of date. Generate C# before using or building this table.";
            } catch (Exception e) { return e.Message; }
        }
    }
    internal sealed class QuestFactCodeImport : AssetPostprocessor
    {
        private static void OnPostprocessAllAssets(string[] imported, string[] deleted, string[] moved, string[] previous)
        {
            foreach (var path in imported.Concat(moved).Where(p => p.EndsWith(".asset", StringComparison.OrdinalIgnoreCase)))
            {
                var table = AssetDatabase.LoadAssetAtPath<QuestFactTable>(path);
                if (table) QuestFactCodeGenerator.Queue(table);
            }
        }
    }
    internal sealed class QuestFactCodeBuildCheck : IPreprocessBuildWithReport
    {
        public int callbackOrder => 0;
        public void OnPreprocessBuild(BuildReport report)
        {
            foreach (var guid in AssetDatabase.FindAssets("t:QuestFactTable"))
            {
                var table = AssetDatabase.LoadAssetAtPath<QuestFactTable>(AssetDatabase.GUIDToAssetPath(guid));
                var error = QuestFactCodeGenerator.Status(table);
                if (!string.IsNullOrEmpty(error)) throw new BuildFailedException(table.name + ": " + error);
            }
        }
    }
}
